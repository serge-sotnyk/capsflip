//! Keys and key events, as the engine sees them.

/// A key, identified by its Windows virtual-key code.
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub struct Key(u16);

impl Key {
    pub const CAPS_LOCK: Self = Self(0x14);
    pub const INSERT: Self = Self(0x2d);
    pub const C: Self = Self(0x43);
    pub const V: Self = Self(0x56);
    pub const X: Self = Self(0x58);
    pub const LWIN: Self = Self(0x5b);
    pub const RWIN: Self = Self(0x5c);
    pub const LSHIFT: Self = Self(0xa0);
    pub const RSHIFT: Self = Self(0xa1);
    pub const LCONTROL: Self = Self(0xa2);
    pub const RCONTROL: Self = Self(0xa3);
    pub const LMENU: Self = Self(0xa4);
    pub const RMENU: Self = Self(0xa5);
    /// An unassigned key that does nothing. Injected around the release of
    /// Win, it keeps that release from opening Start.
    pub const MASK: Self = Self(0xe8);

    #[must_use]
    pub const fn from_vk(code: u16) -> Self {
        Self(code)
    }

    #[must_use]
    pub const fn vk(self) -> u16 {
        self.0
    }

    /// True for keys Windows reports with the extended-key flag. An injected
    /// key must carry it, or Insert arrives as the Insert of the numeric
    /// keypad.
    #[must_use]
    pub const fn extended(self) -> bool {
        matches!(self.0, 0x2d | 0x5b | 0x5c | 0xa3 | 0xa5)
    }
}

/// Which modifier keys are physically held.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
#[allow(clippy::struct_excessive_bools)] // four independent keys, not a state machine
pub struct Modifiers {
    pub shift: bool,
    pub ctrl: bool,
    pub alt: bool,
    pub win: bool,
}

impl Modifiers {
    pub const NONE: Self = Self {
        shift: false,
        ctrl: false,
        alt: false,
        win: false,
    };
    pub const SHIFT: Self = Self {
        shift: true,
        ..Self::NONE
    };
    pub const CTRL: Self = Self {
        ctrl: true,
        ..Self::NONE
    };
    pub const WIN: Self = Self {
        win: true,
        ..Self::NONE
    };
    pub const WIN_SHIFT: Self = Self {
        shift: true,
        ..Self::WIN
    };
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum KeyKind {
    Down,
    Up,
}

/// One keyboard event, with the modifier state at the moment it happened.
///
/// The shell reads the modifiers from the system for every event instead of
/// the engine tracking them, because the hook misses events while an elevated
/// window has the focus and a tracked state would get stuck.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct KeyEvent {
    pub key: Key,
    pub kind: KeyKind,
    pub mods: Modifiers,
    /// True for events generated by software, capsflip's own included.
    pub injected: bool,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_key_is_its_virtual_key_code() {
        assert_eq!(Key::from_vk(0x43), Key::C);
        assert_eq!(Key::C.vk(), 0x43);
        assert_eq!(Key::MASK.vk(), 0xe8, "unassigned, so it does nothing");
    }

    #[test]
    fn insert_win_and_the_right_hand_modifiers_are_extended_keys() {
        for key in [Key::INSERT, Key::LWIN, Key::RWIN, Key::RCONTROL, Key::RMENU] {
            assert!(key.extended(), "{key:?}");
        }
        for key in [
            Key::C,
            Key::CAPS_LOCK,
            Key::LCONTROL,
            Key::LSHIFT,
            Key::RSHIFT,
            Key::LMENU,
            Key::MASK,
        ] {
            assert!(!key.extended(), "{key:?}");
        }
    }

    #[test]
    fn win_shift_is_win_and_shift() {
        assert_eq!(
            Modifiers::WIN_SHIFT,
            Modifiers {
                win: true,
                shift: true,
                ..Modifiers::NONE
            }
        );
        assert_eq!(
            Modifiers::WIN,
            Modifiers {
                win: true,
                ..Modifiers::NONE
            }
        );
    }
}
